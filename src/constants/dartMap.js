/**
 * 종목코드로 DART 기업코드 조회
 * @param {string} code - 종목코드 (예: '005930')
 * @returns {string|null} DART 기업코드 또는 null
 */
export function getDartCorpCode(code) {
  return DART_CORP_MAP[code] || null
}

/**
 * DART 공시 목록 URL 생성
 * @param {string} stockName - 종목명
 * @returns {string} DART 공시 검색 URL
 */
export function getDartSearchUrl(stockName) {
  return `https://dart.fss.or.kr/dsab007/detailSearch.ax?textCrpNm=${encodeURIComponent(stockName)}`
}

/**
 * DART 공시 원문 URL 생성
 * @param {string} rceptNo - 접수번호
 * @returns {string} DART 원문 URL
 */
export function getDartDocUrl(rceptNo) {
  return `https://dart.fss.or.kr/dsaf001/main.do?rcpNo=${rceptNo}`
}
